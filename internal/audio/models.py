"""Data models for audio transcription, speaker diarization, and timeline alignment."""

from dataclasses import dataclass, field


@dataclass
class WordTiming:
    """Normalized word timing projected onto the absolute media timeline."""

    word: str
    start_time: float  # Absolute media timeline timestamp
    end_time: float  # Absolute media timeline timestamp
    confidence: float = 1.0


@dataclass
class SpeakerTurn:
    """Speaker turn interval emitted by PyAnnote diarization engine."""

    speaker_id: str
    start_time: float  # Relative to processed slice
    end_time: float  # Relative to processed slice


@dataclass
class RawWhisperSegment:
    """Raw transcription segment generated by Whisper speech-to-text."""

    text: str
    start_time: float  # Relative to processed slice
    end_time: float  # Relative to processed slice
    words: list[WordTiming] = field(default_factory=list)


# Alias for compatibility with architecture references
RawAudioChunk = RawWhisperSegment


@dataclass
class AlignedTranscriptSegment:
    """Complete transcript segment aligned with speaker turn on the absolute timeline."""

    speaker_id: str
    start_time_seconds: float  # Absolute timeline timestamp
    end_time_seconds: float  # Absolute timeline timestamp
    text: str
    words: list[WordTiming] = field(default_factory=list)
